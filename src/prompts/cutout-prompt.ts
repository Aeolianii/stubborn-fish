import type { ImportedSubjectType } from "../domain/cutout.js";

export function buildCutoutPrompt(
  description: string,
  subjectType: ImportedSubjectType = "other"
): string {
  const requestedSubject = description.trim();
  const target = requestedSubject || "参考图中的主要主体";

  const preservationRule = {
    person:
      "保留原图中实际可见的人物、脸部、发型、衣饰、四肢和姿态；不得改变身份特征，不得补画被遮挡或画面外的身体。",
    aquatic_animal:
      "保留原图中实际可见的水生动物身体、鳍、肢体、尾部、颜色、斑纹和姿态；不得改变品种或身体结构。",
    land_animal:
      "保留原图中实际可见的动物身体、四肢、尾巴、毛发、颜色、斑纹和姿态；不得改造成水生动物，不得添加鱼尾。",
    plant:
      "保留原图中实际可见的植株、枝干、叶片、花朵、颜色和自然边缘；不得补造画面外的枝叶。",
    other:
      "保留原图中实际可见的主体外形、结构、材质、颜色、纹理和朝向；不得改变类别或用途。"
  }[subjectType];

  return [
    "任务：直接参考输入图片进行图生图编辑，把用户指定主体转绘成一张可直接放入鱼缸的单主体插画风动漫形象，输出为供后端色键抠图的贴纸素材。",
    `用户指定目标：${target}`,
    "输入图片是主体外形、身份特征、姿态、朝向、颜色和纹理的唯一视觉依据；必须忠实参考原图，不得仅根据文字重新想象主体。",
    preservationRule,
    "画风：精致二维动漫插画与游戏角色立绘风，线条柔和干净，轮廓清晰，色块完整，细腻赛璐璐上色结合少量柔和渐变，表情自然生动；整体清新、温柔、有亲和力。",
    "动漫化时保留主体最有辨识度的轮廓、比例、姿态、朝向、面部特征、主色、斑纹、发型、服饰和材质特征。允许适度简化细节和美化造型，但不得改变类别，不得添加描述之外的肢体、鱼尾、配件或装饰。",
    "主体必须是完整绘制、有明确颜色和纹理的不透明前景。避免照片感、写实摄影、3D 渲染、塑料质感、厚重油画、粗黑描边、过度夸张的大眼、霓虹高光和杂乱纹理。",
    "最高优先级前景规则：主体轮廓以内的每一个像素都属于前景并必须完全不透明。主体内部不得出现透明洞、半透明破损或被背景色挖空的区域。",
    "白色、米白、浅灰、浅色毛发、白色衣服、眼白、高光和反光全部是主体颜色，必须作为有颜色的实体完整保留，绝不能因为接近白色而变透明。",
    "保留完整主体边缘，不裁掉头发、耳朵、手指、脚、尾巴、鳍、叶片或细小突出结构。边缘应干净自然，禁止白边、黑边、洋红描边、彩色溢边、辉光和背景残留。",
    "需要移除：背景、地面、投影、反光、文字、水印、边框和其他物体。这些内容只用于界定要删除的区域，不得据此修改主体。",
    "主体居中、方向自然，不旋转、不镜像；主体任何部分都不得接触画布四边，四周至少保留约 10% 的纯色安全边距，以便可靠分离背景。",
    "最高优先级背景规则：不要尝试绘制透明效果，也不要生成白底、米色底或透明棋盘格。主体轮廓外的每一个像素都必须填充完全相同的纯 #FF00FF（RGB 255, 0, 255）洋红色。",
    "洋红背景只是机器色键，不是插画内容，绝对禁止对背景做任何艺术化处理：不得出现色差、渐变、阴影、投影、光晕、反光、颗粒、噪点、喷溅、水彩笔触、纸张纹理、云雾、装饰、文字、边框或水印。",
    "主体与纯洋红背景之间必须是清晰、连续、无污染的单一轮廓；主体外不得有零散像素、碎屑、残影或半透明颜色，主体边缘不得沾染洋红色。",
    "输出前逐项自检：背景从四角到主体边缘都是同一个 #FF00FF；没有任何粉色纹理或斑点；主体内部颜色完整，特别是所有白色和浅色区域仍为完全不透明前景。"
  ].join("\n");
}
